import { getActiveScope, type ApexScope } from "./scope.js";

export type SdkLanguage = "typescript" | "python" | "dart" | "go";

export interface SdkGenerateOptions {
  language: SdkLanguage;
  baseUrl?: string;
  scope?: ApexScope;
  clientName?: string;
}

function pathToMethodName(path: string, method: string): string {
  // Convert /api/v1/users/:id to getUsersById
  const clean = path.replace(/^\//, "").replace(/\/$/, "");
  const segments = clean.split("/").filter((s) => s.length > 0 && !s.startsWith(":"));
  const params = clean.split("/").filter((s) => s.startsWith(":")).map((s) => s.slice(1));

  let name = method.toLowerCase();
  for (const seg of segments) {
    if (seg === "api" || seg === "v1" || seg === "v2") continue;
    name += seg.charAt(0).toUpperCase() + seg.slice(1);
  }

  if (params.length > 0) {
    name += "By" + params.map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join("And");
  }

  return name || `${method.toLowerCase()}Root`;
}

function extractPathParams(path: string): string[] {
  const matches = path.match(/:([a-zA-Z0-9_]+)/g);
  return matches ? matches.map((m) => m.slice(1)) : [];
}

export class ApexSdkEngine {
  public generate(options: SdkGenerateOptions): string {
    const scope = options.scope || getActiveScope();
    const baseUrl = options.baseUrl || "http://localhost:3000";
    const clientName = options.clientName || "ApexClient";

    // Filter out internal routes
    const routes = scope.routesManifest.filter((r) => {
      const p = r.path;
      return !p.startsWith("/_docs") && !p.startsWith("/_studio") && !p.startsWith("/_openapi") && !p.startsWith("/_mcp");
    });

    switch (options.language) {
      case "typescript":
        return this.generateTypeScript(routes, baseUrl, clientName);
      case "python":
        return this.generatePython(routes, baseUrl, clientName);
      case "dart":
        return this.generateDart(routes, baseUrl, clientName);
      case "go":
        return this.generateGo(routes, baseUrl, clientName);
      default:
        throw new Error(`Unsupported SDK language '${options.language}'`);
    }
  }

  private generateTypeScript(routes: any[], baseUrl: string, clientName: string): string {
    const methods = routes.map((r) => {
      const methodName = pathToMethodName(r.path, r.method);
      const params = extractPathParams(r.path);
      const hasBody = ["POST", "PUT", "PATCH"].includes(r.method);

      const argList: string[] = [];
      for (const p of params) argList.push(`${p}: string | number`);
      if (hasBody) argList.push("body?: any");
      argList.push("options: RequestInit = {}");

      let pathExpr = `\`${r.path.replace(/:([a-zA-Z0-9_]+)/g, "${$1}")}\``;

      return `  public async ${methodName}(${argList.join(", ")}): Promise<any> {
    const url = this.baseUrl + ${pathExpr};
    const res = await fetch(url, {
      ...options,
      method: "${r.method}",
      headers: {
        "content-type": "application/json",
        ...(options.headers || {})
      }${hasBody ? ',\n      body: body ? JSON.stringify(body) : undefined' : ""}
    });
    if (!res.ok) {
      throw new Error(\`HTTP \${res.status} \${res.statusText}\`);
    }
    const ct = res.headers.get("content-type") || "";
    return ct.includes("application/json") ? await res.json() : await res.text();
  }`;
    }).join("\n\n");

    return `// Auto-generated by APEX14 SDK Engine
export class ${clientName} {
  constructor(public baseUrl: string = "${baseUrl}") {}

${methods}
}
`;
  }

  private generatePython(routes: any[], baseUrl: string, clientName: string): string {
    const methods = routes.map((r) => {
      const pyMethodName = pathToMethodName(r.path, r.method)
        .replace(/([A-Z])/g, "_$1")
        .toLowerCase();
      const params = extractPathParams(r.path);
      const hasBody = ["POST", "PUT", "PATCH"].includes(r.method);

      const argList = ["self"];
      for (const p of params) argList.push(`${p}: str`);
      if (hasBody) argList.push("body: dict = None");
      argList.push("headers: dict = None");

      let pathExpr = `f"${r.path.replace(/:([a-zA-Z0-9_]+)/g, "{$1}")}"`;

      return `    def ${pyMethodName}(${argList.join(", ")}) -> dict:
        url = self.base_url + ${pathExpr}
        req_headers = {"Content-Type": "application/json"}
        if headers:
            req_headers.update(headers)
        data = json.dumps(body).encode("utf-8") if body else None
        req = urllib.request.Request(url, data=data, headers=req_headers, method="${r.method}")
        with urllib.request.urlopen(req) as resp:
            return json.loads(resp.read().decode("utf-8"))`;
    }).join("\n\n");

    return `# Auto-generated by APEX14 SDK Engine
import json
import urllib.request

class ${clientName}:
    def __init__(self, base_url: str = "${baseUrl}"):
        self.base_url = base_url

${methods}
`;
  }

  private generateDart(routes: any[], baseUrl: string, clientName: string): string {
    const methods = routes.map((r) => {
      const methodName = pathToMethodName(r.path, r.method);
      const params = extractPathParams(r.path);
      const hasBody = ["POST", "PUT", "PATCH"].includes(r.method);

      const argList: string[] = [];
      for (const p of params) argList.push(`String ${p}`);
      if (hasBody) argList.push("dynamic body");
      argList.push("Map<String, String>? headers");

      let pathExpr = `'$baseUrl${r.path.replace(/:([a-zA-Z0-9_]+)/g, "$$$1")}'`;

      return `  Future<dynamic> ${methodName}(${argList.join(", ")}) async {
    final uri = Uri.parse(${pathExpr});
    final reqHeaders = {'content-type': 'application/json', ...?headers};
    final res = await client.${r.method.toLowerCase()}(
      uri,
      headers: reqHeaders,
      ${hasBody ? "body: body != null ? jsonEncode(body) : null," : ""}
    );
    if (res.statusCode >= 400) {
      throw Exception('HTTP \${res.statusCode}: \${res.body}');
    }
    return jsonDecode(res.body);
  }`;
    }).join("\n\n");

    return `// Auto-generated by APEX14 SDK Engine
import 'dart:convert';
import 'package:http/http.dart' as http;

class ${clientName} {
  final String baseUrl;
  final http.Client client;

  ${clientName}({this.baseUrl = '${baseUrl}', http.Client? client})
      : client = client ?? http.Client();

${methods}
}
`;
  }

  private generateGo(routes: any[], baseUrl: string, clientName: string): string {
    const methods = routes.map((r) => {
      const rawName = pathToMethodName(r.path, r.method);
      const methodName = rawName.charAt(0).toUpperCase() + rawName.slice(1);
      const params = extractPathParams(r.path);
      const hasBody = ["POST", "PUT", "PATCH"].includes(r.method);

      const argList = ["ctx context.Context"];
      for (const p of params) argList.push(`${p} string`);
      if (hasBody) argList.push("body interface{}");

      let pathExpr = `fmt.Sprintf("${r.path.replace(/:([a-zA-Z0-9_]+)/g, "%s")}", ${params.join(", ")})`;
      if (params.length === 0) {
        pathExpr = `"${r.path}"`;
      }

      return `func (c *${clientName}) ${methodName}(${argList.join(", ")}) ([]byte, error) {
	endpoint := c.BaseURL + ${pathExpr}
	var bodyReader io.Reader
	if body != nil {
		data, err := json.Marshal(body)
		if err != nil {
			return nil, err
		}
		bodyReader = bytes.NewReader(data)
	}
	req, err := http.NewRequestWithContext(ctx, "${r.method}", endpoint, bodyReader)
	if err != nil {
		return nil, err
	}
	req.Header.Set("Content-Type", "application/json")
	resp, err := c.HTTPClient.Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	return io.ReadAll(resp.Body)
}`;
    }).join("\n\n");

    return `// Auto-generated by APEX14 SDK Engine
package sdk

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
)

type ${clientName} struct {
	BaseURL    string
	HTTPClient *http.Client
}

func New${clientName}(baseURL string) *${clientName} {
	if baseURL == "" {
		baseURL = "${baseUrl}"
	}
	return &${clientName}{
		BaseURL:    baseURL,
		HTTPClient: http.DefaultClient,
	}
}

${methods}
`;
  }
}

export const sdk = new ApexSdkEngine();
